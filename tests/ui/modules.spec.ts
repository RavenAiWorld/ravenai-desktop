import { test, expect, type Page } from '@playwright/test'
import { setup } from './fixture'

const nav = (page: Page, label: string) => page.getByRole('navigation', { name: '主要导航' }).getByRole('button', { name: label, exact: true }).click()

test('embedded channel status uses observed data, changes resolution, and opens native model plaza', async ({ page }) => {
  await setup(page); await page.goto('/'); await nav(page, '渠道状态')
  await expect(page.getByRole('heading', { name: '渠道状态', exact: true })).toBeVisible()
  await expect(page.locator('.channel-state').first()).toHaveText('正常')
  await expect(page.locator('.channel-tps').first()).toContainText('tok/s')
  await expect(page.locator('.channel-timeline .history-slot')).toHaveCount(24)
  await page.getByRole('button', { name: '1 小时', exact: true }).click()
  await expect(page.locator('.channel-timeline .history-slot')).toHaveCount(6)
  await page.getByRole('button', { name: /OpenAI 标准线路/ }).click()
  await expect(page.getByRole('cell', { name: '99.50%' })).toBeVisible()
  await page.screenshot({ path: 'qa-results/channel-status.png' })
  await page.getByRole('button', { name: '查看模型与价格' }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('模型广场')
  await expect(page.getByLabel('模型分组')).toHaveValue('1')
  expect(await page.evaluate(() => (window as any).qa.calls.filter((c: any) => c.command === 'open_site'))).toEqual([])
})

