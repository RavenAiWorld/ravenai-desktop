test('redemption preserves failed codes and updates balance only on success', async ({ page }) => {
  await setup(page); await page.goto('/'); await nav(page, '兑换额度')
  await page.getByLabel('兑换码', { exact: true }).fill('isolated-test-code')
  await page.evaluate(() => { (window as any).qa.failures['/redeem'] = '兑换码无效或已使用' })
  await page.getByRole('button', { name: '兑换', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('兑换码无效或已使用')
  await expect(page.getByLabel('兑换码', { exact: true })).toHaveValue('isolated-test-code')
  await page.evaluate(() => { delete (window as any).qa.failures['/redeem'] })
  await page.getByRole('button', { name: '兑换', exact: true }).click()
  await expect(page.locator('.redemption-result')).toContainText('当前余额 $38.50')
  await expect(page.getByLabel('兑换码', { exact: true })).toHaveValue('')
  await expect(page.locator('.module-summary')).toContainText('$38.50')
  await page.screenshot({ path: 'qa-results/redemption.png' })
  expect(await page.evaluate(() => (window as any).qa.calls.filter((c: any) => c.command === 'open_site'))).toEqual([])
})

